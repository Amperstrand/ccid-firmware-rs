#!/usr/bin/env python3
"""boltwipe — NTAG424 DNA card verify/wipe driver over PC/SC.

Byte-exact port of the bolt-card-programmer app's NTag424.tsx secure
messaging, hardware-proven on 2026-08-25 (full wipe of a live card,
including recovery from an interrupted wipe). Reference APDUs for the
selftest are generated by bolt-card-programmer/refchangekey.js from the
app's own crypto (lesson B8: port wire-format crypto byte-for-byte, then
pin it with vectors from the original implementation).

Requires: pycryptodome, pyscard, any PC/SC reader (e.g. the esp32-ccid
firmware from this repo on a suitably-wired ESP32).

Usage:
  boltwipe.py selftest                          # offline vector check
  boltwipe.py verify --uid HEX --k1 HEX --k2 HEX
      Read-only: UID gate, NDEF URL, offline tap verdict (decrypt p under
      K1, CMAC-verify c under K2). Proves keys with ZERO card auth.
  boltwipe.py wipe --uid HEX --keys k0,k1,k2,k3,k4 [--resume-from N]
      EV2 auth with K0 (proved via GetCardUid) -> reset file settings ->
      ChangeKey 1..4 -> zeros -> ChangeKey 0 LAST -> clear NDEF + tail.
      --resume-from N: continue an interrupted wipe at key N (1-4, or 0).

Card-safety notes (bolty-rs docs/lessons-learned.md B6/B7):
  - Only failed AUTHENTICATION (91AE/91AD) feeds the lockout counter;
    in-session 911E does not. This driver never guesses keys.
  - A ChangeKey rejection for key N proves the staged old key N is wrong:
    STOP and re-source the keys (they may live beyond a truncated log line).
"""
