#!/usr/bin/env python3
"""Unit tests for scripts/status_drift.py — stdlib only (the minimal CI
env runs them: no pytest, no network, no git). Locks the #183 drift
contract: stamp parsing, path→target classification (the ci.yml
mirror), and the STALE/current rendering.

    python3 scripts/test_status_drift.py
"""

import importlib.util
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

_SRC = Path(__file__).resolve().parent / "status_drift.py"
_spec = importlib.util.spec_from_file_location("status_drift", _SRC)
drift = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(drift)


class StampParsingTests(unittest.TestCase):
    def test_extracts_the_verified_commit(self):
        # The nightly's exact stamp shape (gen_status.py render):
        self.assertEqual(
            drift.STAMP_RE.search(
                "Verified: 2026-10-17T03:31:18Z @ `0f45f31743e9` — `bench_inventory.py`"
            ).group(1),
            "0f45f31743e9",
        )

    def test_no_stamp_is_none(self):
        self.assertIsNone(drift.STAMP_RE.search("no stamp here"))


class ClassificationTests(unittest.TestCase):
    def test_stm32_paths_hit_stm32_target(self):
        self.assertIn(
            "stm32-f469-f746",
            drift.classify(["firmware/ccid-firmware/src/main.rs", "CHANGELOG.md"]),
        )

    def test_display_path_is_stm32(self):
        # The #193 fixture: the display resurrection lived in
        # firmware/ccid-firmware + vendor/ — must flag stm32 targets.
        self.assertIn(
            "stm32-f469-f746",
            drift.classify(["vendor/stm32f469i-disc/src/display.rs"]),
        )

    def test_nucula_paths_flag_nucula_and_shared(self):
        t = drift.classify(["firmware/esp32-ccid/src/pn7160_ccid.rs"])
        self.assertIn("esp32-nucula", t)
        self.assertIn("esp32-shared", t)

    def test_m5stick_paths_flag_m5stick_and_shared(self):
        t = drift.classify(["firmware/esp32-ccid/src/mfrc522_driver.rs"])
        self.assertIn("esp32-m5stick", t)
        self.assertIn("esp32-shared", t)

    def test_shared_crate_change_flags_both_targets(self):
        # Codex P2 on #234: ci.yml's stm32 filter includes crates/** —
        # a shared-crate change must stale BOTH stm32 and esp32 rows.
        t = drift.classify(["crates/ccid-core/src/handler.rs"])
        self.assertIn("stm32-f469-f746", t)
        self.assertIn("esp32-shared", t)

    def test_docs_only_touches_nothing(self):
        self.assertEqual(drift.classify(["docs/SOME.md", "AGENTS.md"]), set())

    def test_bench_infra_paths_flag_infra(self):
        self.assertIn("bench-infra", drift.classify(["tests/hardware/nfc/x.py"]))


class RenderTests(unittest.TestCase):
    def test_stale_target_rows_and_details(self):
        rows = {
            "stm32-f469-f746": [
                ("365e35d12345", "fix(#193): display"),
                ("aaaabbbcccc", "docs: thing"),
            ]
        }
        body = drift.render("0f45f31743e9", "718e014352aa5d", rows, 2)
        self.assertIn("| stm32-f469-f746 | 2 | fix(#193): display | ⚠️ STALE |", body)
        self.assertIn("`365e35d12345` fix(#193): display", body)
        self.assertIn("GENERATED by scripts/status_drift.py", body)

    def test_no_drift_renders_current(self):
        body = drift.render("abc", "def", {}, 0)
        self.assertIn("| (none) | 0 | — | ✅ current |", body)
        self.assertNotIn("STALE", body)


class PrintBenchCommitModeTests(unittest.TestCase):
    def test_prints_only_the_sha_from_real_shaped_stamp(self):
        # The nightly's extraction hook: real bench/status stamps wrap
        # the SHA in backticks — the shell grep that missed them was
        # the 2026-10-17 dormant-drift bug this mode replaces.
        with tempfile.TemporaryDirectory() as d:
            st = Path(d) / "STATUS.md"
            st.write_text("...\nVerified: 2026-10-17T03:31:18Z @ `0f45f31743e9` — `bench_inventory.py`\n")
            r = subprocess.run(
                [sys.executable, str(_SRC), "--print-bench-commit", "--from-status", str(st)],
                capture_output=True, text=True, timeout=30,
            )
            self.assertEqual(r.returncode, 0)
            self.assertEqual(r.stdout.strip(), "0f45f31743e9")

    def test_no_stamp_prints_nothing_exit_zero(self):
        with tempfile.TemporaryDirectory() as d:
            st = Path(d) / "STATUS.md"
            st.write_text("no stamps here\n")
            r = subprocess.run(
                [sys.executable, str(_SRC), "--print-bench-commit", "--from-status", str(st)],
                capture_output=True, text=True, timeout=30,
            )
            self.assertEqual(r.returncode, 0)
            self.assertEqual(r.stdout.strip(), "")


if __name__ == "__main__":
    unittest.main()
