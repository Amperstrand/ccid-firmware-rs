#!/usr/bin/env python3
r"""Staleness layer for the generated STATUS.md (#183 wave D).

gen_status.py answers "what did the last bench run prove, and when";
it cannot answer "has firmware landed SINCE, making those claims
stale?" — the #193 class (display fix merged 10-15, bench verified
10-17: two days of silently stale hardware claims, noticed only when
the issue triage touched it).

This script diffs the commit the last bench STATUS was generated at
against current HEAD, classifies every landed commit to its hardware
targets (path map mirrored from ci.yml's stm32/esp32 filters), and
emits a DRIFT section: per target, the commits awaiting bench
verification, with a staleness flag when any exist. Output is a
markdown fragment designed to be APPENDED by the nightly's status job
(or run standalone: `make status-drift`).

    python3 scripts/status_drift.py --repo . \
        --bench-commit 0f45f31 [--head origin/main] [--out drift.md]

`--bench-commit` comes from the STATUS.md stamp (`Verified: ... @
\`<sha>\``) — parseable via --from-status for a pipeline handoff.
Exit 0 always (status tooling never fails the run that reports status).
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

# Path → target classification, mirroring ci.yml's changes-filter sets
# (single source of truth: if CI builds it for stm32/esp32, bench
# verification for that target is stale when it changes).
TARGET_PATHS: dict[str, tuple[str, ...]] = {
    # Full ci.yml stm32 filter mirror (Codex P2 on #234): shared
    # crates + workspace inputs flag BOTH targets, like the CI filter.
    "stm32-f469-f746": (
        "firmware/ccid-firmware/",
        "vendor/",
        "crates/",
        "Cargo.toml",
        "Cargo.lock",
        ".cargo/",
        "host-tools/",
    ),
    "esp32-m5stick": (
        "firmware/esp32-ccid/src/mfrc522_driver.rs",
        "firmware/esp32-ccid/src/m5stick_lcd.rs",
        "firmware/esp32-ccid/src/led.rs",
    ),
    "esp32-nucula": (
        "firmware/esp32-ccid/src/pn7160_",
        "firmware/esp32-ccid/src/vpcd.rs",
        "firmware/esp32-ccid/src/wifi_",
    ),
    "esp32-shared": (
        "firmware/esp32-ccid/",
        "crates/",
        "Cargo.toml",
        "Cargo.lock",
        ".cargo/",
    ),
    "bench-infra": (
        "tests/hardware/",
        "tools/",
        "scripts/gen_status.py",
    ),
}

STAMP_RE = re.compile(r"Verified: .* @ `([0-9a-f]{7,40})`")


def git(repo: Path, *args: str) -> str:
    r = subprocess.run(
        ["git", "-C", str(repo), *args], capture_output=True, text=True, timeout=60
    )
    return r.stdout if r.returncode == 0 else ""


def git_ok(repo: Path, *args: str) -> bool:
    r = subprocess.run(
        ["git", "-C", str(repo), *args], capture_output=True, text=True, timeout=60
    )
    return r.returncode == 0


def bench_commit_from_status(path: Path) -> str | None:
    m = STAMP_RE.search(path.read_text(encoding="utf-8", errors="replace"))
    return m.group(1) if m else None


def commits_between(repo: Path, since: str, head: str) -> list[tuple[str, str, list[str]]]:
    """[(sha, subject, [files])] for commits in (since, head], newest first."""
    out: list[tuple[str, str, list[str]]] = []
    for entry in git(repo, "log", "--reverse", "--format=%H%x00%s", f"{since}..{head}").split("\n"):
        if not entry:
            continue
        sha, subject = entry.split("\x00", 1)
        files = git(repo, "show", "--name-only", "--format=", sha).splitlines()
        out.append((sha[:12], subject, [f for f in files if f]))
    return out


def classify(files: list[str]) -> set[str]:
    targets: set[str] = set()
    for target, prefixes in TARGET_PATHS.items():
        for f in files:
            if f.startswith(prefixes):
                targets.add(target)
                break
    return targets


def render(bench_commit: str, head: str, rows: dict[str, list[tuple[str, str]]], n_commits: int) -> str:
    lines = [
        "<!-- GENERATED by scripts/status_drift.py (#183) — drift layer, never edit. -->",
        "## Bench-evidence drift (since the last STATUS stamp)",
        "",
        f"Last bench verified main @ `{bench_commit[:12]}`; this report @ `{head[:12]}` "
        f"({n_commits} commits between). A target listed below has firmware landed "
        "AFTER its last on-hardware verification — its STATUS rows are stale until "
        "the next bench run.",
        "",
        "| target | commits awaiting bench | oldest | flag |",
        "|---|---|---|---|",
    ]
    if not rows:
        lines.append("| (none) | 0 | — | ✅ current |")
    for target in sorted(rows):
        cs = rows[target]
        oldest = cs[0][1]  # oldest first (git log --reverse)
        lines.append(f"| {target} | {len(cs)} | {oldest} | ⚠️ STALE |")
    lines.append("")
    for target in sorted(rows):
        lines.append(f"<details><summary>{target}: {len(rows[target])} commits</summary>")
        lines.append("")
        for sha, subject in rows[target]:
            lines.append(f"- `{sha}` {subject}")
        lines.append("")
        lines.append("</details>")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo", type=Path, default=Path("."))
    ap.add_argument("--bench-commit", help="commit the last bench STATUS verified")
    ap.add_argument("--from-status", type=Path, help="parse --bench-commit from a STATUS.md stamp")
    ap.add_argument("--head", default="HEAD")
    ap.add_argument("--out", type=Path, help="write the drift section here (default: stdout)")
    args = ap.parse_args()

    bench = args.bench_commit
    if not bench and args.from_status and args.from_status.is_file():
        bench = bench_commit_from_status(args.from_status)
    if not bench:
        print("status_drift: no bench commit (give --bench-commit or --from-status) — no-op", file=sys.stderr)
        return 0

    head = git(args.repo, "rev-parse", args.head).strip()
    if not head or not git_ok(args.repo, "merge-base", "--is-ancestor", bench, head):
        print(f"status_drift: {bench}..{head} not a fast-forward range — no-op", file=sys.stderr)
        return 0

    commits = commits_between(args.repo, bench, head)
    rows: dict[str, list[tuple[str, str]]] = {}
    for sha, subject, files in commits:
        for target in classify(files):
            rows.setdefault(target, []).append((sha, subject))

    body = render(bench, head, rows, len(commits))
    if args.out:
        args.out.write_text(body + "\n", encoding="utf-8")
        print(f"status_drift: {len(rows)} stale target(s) -> {args.out}", file=sys.stderr)
    else:
        print(body)
    return 0


if __name__ == "__main__":
    sys.exit(main())
